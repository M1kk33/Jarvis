"""Replaceable seams for M3 lifecycle behavior."""

from collections.abc import Awaitable
from threading import Event
from typing import Protocol

from jarvis.domain.resources import ResourceSnapshot, RuntimeIdentity, RuntimeProfile


class ResourceProbe(Protocol):
    def snapshot(self) -> ResourceSnapshot: ...


class Clock(Protocol):
    def now(self) -> float: ...
    def sleep(self, seconds: float) -> Awaitable[None]: ...


class ManagedRuntime(Protocol):
    async def start(
        self, profile: RuntimeProfile, generation: int, cancel: Event, job_name: str
    ) -> RuntimeIdentity: ...
    async def stop(self, identity: RuntimeIdentity) -> bool: ...
    async def abort_start(self, generation: int) -> bool: ...
    async def wait_exit(self, identity: RuntimeIdentity) -> None: ...
    async def verify_stopped(self, identity: RuntimeIdentity) -> bool: ...


class OwnershipLock(Protocol):
    async def acquire(self) -> bool:
        """Return whether a previous owner abandoned the named lock."""

    async def verify_previous(self, abandoned: bool) -> bool: ...
    async def record_spawn_intent(self, generation: int) -> str: ...
    async def record_running(self, identity: RuntimeIdentity) -> None: ...
    async def clear(self) -> None: ...
    async def release(self) -> None: ...
